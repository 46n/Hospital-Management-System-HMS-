    private void saveProfile() {
    try {
        User user = sessionManager.getCurrentUser();
        if (user == null) {
            throw new IllegalStateException(
                    "No user is currently logged in"
            );
        }
        String phone = PhoneTf.getText().trim();
        String email = EmailTf.getText().trim();
        String currentPassword =
                new String(CurrentPasswordPf.getPassword());
        String newPassword =
                new String(NewPasswordPf.getPassword());
        String confirmPassword =
                new String(ConfirmPasswordPf.getPassword());

        // One atomic manager call: phone, email, and an optional password change are all
        // validated first and saved together, so a bad password field can never leave an
        // already-saved phone/email change behind.
        userManager.updateOwnProfile(
                user.getUserId(),
                phone,
                email,
                currentPassword,
                newPassword,
                confirmPassword
        );
        JOptionPane.showMessageDialog(
                this,
                "Profile updated successfully.",
                "Success",
                JOptionPane.INFORMATION_MESSAGE
        );
        loadCurrentUser();
    } catch (IllegalArgumentException | IllegalStateException ex) {
        JOptionPane.showMessageDialog(
                this,
                ex.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
}
    
    
    
    
    private void togglePasswordVisibility() {
    if (chkShowPassword.isSelected()) {
        CurrentPasswordPf.setEchoChar((char) 0);
        NewPasswordPf.setEchoChar((char) 0);
        ConfirmPasswordPf.setEchoChar((char) 0);
    } else {
        CurrentPasswordPf.setEchoChar(passwordEchoChar);
        NewPasswordPf.setEchoChar(passwordEchoChar);
        ConfirmPasswordPf.setEchoChar(passwordEchoChar);
    }
}
    
