    private void attemptLogin() {
        if (!validateRequiredFields()) {
            return;
        }
    try {
        String username =
                UsernameTf.getText().trim();
        String password =
                new String(PasswordPf.getPassword());
        User user =
                sessionManager.login(
                        username,
                        password
                );

        PasswordPf.setText("");
        dispose();
        onSuccess.accept(user);
    } catch (IllegalArgumentException ex) {
        JOptionPane.showMessageDialog(
                this,
                ex.getMessage(),
                "Login Failed",
                JOptionPane.ERROR_MESSAGE
        );
        PasswordPf.setText("");
        PasswordPf.requestFocusInWindow();
    }
}
    
    
    private void setupLoginListeners() {

    UsernameTf.addActionListener(e -> {
        PasswordPf.requestFocusInWindow();
    });

    PasswordPf.addActionListener(e -> {
        btnLogin.doClick();
    });
}
    
    
    private void togglePasswordVisibility() {

    if (chkShowPassword.isSelected()) {
        PasswordPf.setEchoChar((char) 0);
    } else {
        PasswordPf.setEchoChar(passwordEchoChar);
    }
}
    
    
    
    private boolean validateRequiredFields() {

    String username = UsernameTf.getText().trim();
    String password = new String(PasswordPf.getPassword());

    lblLoginError.setText("");

    if (username.isEmpty() && password.isEmpty()) {
        lblLoginError.setText("Username and password are required.");
        return false;
    }

    if (username.isEmpty()) {
        lblLoginError.setText("Username is required.");
        return false;
    }

    if (password.isEmpty()) {
        lblLoginError.setText("Password is required.");
        return false;
    }

    return true;
}
    
    
