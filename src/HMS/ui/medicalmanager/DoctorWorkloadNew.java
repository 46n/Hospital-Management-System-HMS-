    private MedicalManager getCurrentManager() {
    sessionManager.requireRole("MEDICAL_MANAGER");
    User currentUser = sessionManager.getCurrentUser();
    if (!(currentUser instanceof MedicalManager)) {
        throw new IllegalStateException(
                "Current user is not a Medical Manager"
        );
    }
    return (MedicalManager) currentUser;
    }
    
    
    private void refreshWorkload() {
    try {
        MedicalManager manager =
                getCurrentManager();
        List<Doctor> doctors =
                shiftManager.getManagedDoctors(
                        manager.getManagerId()
                );
        DefaultTableModel model =
                (DefaultTableModel) tblWorkload.getModel();
        model.setRowCount(0);
        for (Doctor doctor : doctors) {
            // Do not monitor deactivated doctor accounts
            if (!doctor.isActive()) {
                continue;
            }
            int shiftCount =
                    shiftManager.getUpcomingShiftCount(
                            doctor.getDoctorId(),
                            MONITORING_DAYS
                    );
            double totalHours =
                    shiftManager.getUpcomingShiftHours(
                            doctor.getDoctorId(),
                            MONITORING_DAYS
                    );
            String status =
                    shiftManager.getWorkloadStatus(
                            doctor.getDoctorId(),
                            MONITORING_DAYS
                    );
            model.addRow(
                    new Object[]{
                        doctor.getDoctorId(),
                        doctor.getUsername(),
                        shiftCount,
                        totalHours,
                        status
                    }
            );
        }
        loadAlerts(manager);

    } catch (IllegalArgumentException
            | IllegalStateException ex) {

        showError(ex.getMessage());
    }
}
    
    
    private void loadAlerts(
        MedicalManager manager) {
    List<String> alerts =
            shiftManager.getSchedulingAlerts(
                    manager.getManagerId(),
                    MONITORING_DAYS
            );
    if (alerts.isEmpty()) {
        txtAlerts.setText(
                "No scheduling alerts for the next 7 days."
        );
        return;
    }
    StringBuilder text =
            new StringBuilder();

    for (String alert : alerts) {
        text.append("• ")
                .append(alert)
                .append("\n");
    }
    txtAlerts.setText(
            text.toString().trim()
    );
    txtAlerts.setCaretPosition(0);
}
    
    
    private void goBack() {

    if (onBack != null) {
        onBack.run();
    }
}
    
    private void showError(String message) {

    JOptionPane.showMessageDialog(
            this,
            message,
            "Error",
            JOptionPane.ERROR_MESSAGE
    );
}

