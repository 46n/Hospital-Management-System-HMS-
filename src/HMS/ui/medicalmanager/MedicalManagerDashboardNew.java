   private void openAssessmentTypes() {
    mainFrame.showPanel(
        new AssessmentTypeManagementNew(
            sessionManager,
            typeManager,
            () -> mainFrame.showPanel(this)
        )
    );
}

    private void openDoctorShifts() {
     mainFrame.showPanel(
         new DoctorShiftManagementNew(
             sessionManager,
             userManager,
             shiftManager,
             () -> mainFrame.showPanel(this)
         )
     );
 }

    private void openReports() {
    mainFrame.showPanel(
        new ReportViewNew(
            reportManager,
            appointmentManager,
            billingManager,
            clinicalManager,
            typeManager,
            shiftManager,
            userManager,
            () -> mainFrame.showPanel(this)
        )
    );
}
    
    
    private void openClinicalDepartments() {
    mainFrame.showPanel(
        new ClinicalDepartmentManagementNew(
            departmentManager,
            userManager,
            () -> mainFrame.showPanel(this)
        )
    );
}


