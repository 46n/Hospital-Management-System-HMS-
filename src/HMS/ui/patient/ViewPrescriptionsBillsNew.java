    private void loadPrescriptions() {

    DefaultTableModel model =
            (DefaultTableModel) tblPrescriptions.getModel();

    model.setRowCount(0);

    try {

        List<Prescription> prescriptions =
                prescriptionsBillsController.getMyPrescriptions();

        for (Prescription prescription : prescriptions) {

            String doctor =
                    prescription.getDoctor() != null
                            ? prescription.getDoctor().getUsername()
                            : "";

            String date =
                    prescription.getPrescribedDate() != null
                            ? dateFormat.format(
                                    prescription.getPrescribedDate())
                            : "";

            model.addRow(new Object[]{
                prescription.getPrescriptionId(),
                prescription.getMedicationDetails(),
                prescription.getDosage(),
                prescription.getInstructions(),
                doctor,
                date
            });
        }

    } catch (IllegalStateException ex) {

        JOptionPane.showMessageDialog(
                this,
                ex.getMessage(),
                "Unable to Load Prescriptions",
                JOptionPane.ERROR_MESSAGE
        );
    }
}
    private void loadBills() {

    DefaultTableModel model =
            (DefaultTableModel) tblBills.getModel();

    model.setRowCount(0);

    try {

        List<Payment> bills =
                prescriptionsBillsController.getMyBills();

        for (Payment payment : bills) {

            String date =
                    payment.getPaymentDate() != null
                            ? dateFormat.format(
                                    payment.getPaymentDate())
                            : "";

            model.addRow(new Object[]{
                payment.getPaymentId(),
                prescriptionsBillsController
                        .getAppointmentDisplay(payment),
                String.format("%.2f", payment.getAmount()),
                payment.getStatus(),
                date
            });
        }

    } catch (IllegalStateException ex) {

        JOptionPane.showMessageDialog(
                this,
                ex.getMessage(),
                "Unable to Load Bills",
                JOptionPane.ERROR_MESSAGE
        );
    }
}

