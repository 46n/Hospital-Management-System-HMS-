private void loadMedicalHistory() {

    DefaultTableModel model =
            (DefaultTableModel) tblMedicalRecords.getModel();

    model.setRowCount(0);
    txtRecordDetails.setText("");

    try {

        records =
                medicalHistoryController.getMyMedicalRecords();

        for (MedicalRecord record : records) {

            String doctor =
                    record.getDoctor() != null
                            ? record.getDoctor().getUsername()
                            : "";

            String appointmentDate = "";

            if (record.getAppointment() != null
                    && record.getAppointment().getAppointmentDate() != null) {

                appointmentDate =
                        dateFormat.format(
                                record.getAppointment()
                                        .getAppointmentDate()
                        );
            }

            String diagnosis =
                    record.getDiagnosis() != null
                            ? record.getDiagnosis()
                            : "";

            model.addRow(new Object[]{
                record.getRecordId(),
                doctor,
                appointmentDate,
                diagnosis
            });
        }

    } catch (IllegalStateException ex) {

        JOptionPane.showMessageDialog(
                this,
                ex.getMessage(),
                "Unable to Load Medical History",
                JOptionPane.ERROR_MESSAGE
        );
    }
}
private void showSelectedRecord() {

    int row = tblMedicalRecords.getSelectedRow();

    if (row < 0 || row >= records.size()) {
        txtRecordDetails.setText("");
        return;
    }

    MedicalRecord record = records.get(row);

    txtRecordDetails.setText(
            medicalHistoryController.getRecordDetails(record)
    );

    txtRecordDetails.setCaretPosition(0);
}


